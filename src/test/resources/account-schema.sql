CREATE TABLE IF NOT EXISTS users (
    uid BIGINT AUTO_INCREMENT PRIMARY KEY,
    email VARCHAR_IGNORECASE(100) NOT NULL,
    nickname VARCHAR(50) NOT NULL,
    password VARCHAR(255) NOT NULL,
    permission INT NOT NULL DEFAULT 0,
    score INT NOT NULL DEFAULT 0,
    ip VARCHAR(45) NOT NULL DEFAULT '',
    register_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_sign_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    verified BOOLEAN NOT NULL DEFAULT FALSE,
    avatar INT NOT NULL DEFAULT 0,
    verification_token VARCHAR(255) NOT NULL DEFAULT '',
    remember_token VARCHAR(100),
    locale VARCHAR(255),
    is_dark_mode BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE TABLE IF NOT EXISTS players (
    pid BIGINT AUTO_INCREMENT PRIMARY KEY,
    uid BIGINT NOT NULL,
    name VARCHAR_IGNORECASE(50) NOT NULL,
    tid_skin INT NOT NULL DEFAULT 0,
    tid_cape INT NOT NULL DEFAULT 0,
    last_modified TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS options (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    option_name VARCHAR(50) NOT NULL,
    option_value TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS uuid (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    name VARCHAR_IGNORECASE(255) NOT NULL,
    uuid VARCHAR(255) NOT NULL
);
CREATE TABLE IF NOT EXISTS textures (
    tid INT AUTO_INCREMENT PRIMARY KEY,
    name VARCHAR(50) NOT NULL,
    type VARCHAR(10) NOT NULL,
    hash VARCHAR(64) NOT NULL,
    size INT NOT NULL,
    uploader BIGINT NOT NULL,
    public BOOLEAN NOT NULL,
    upload_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    likes INT NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS user_closet (
    user_uid BIGINT NOT NULL,
    texture_tid INT NOT NULL,
    item_name TEXT
);
