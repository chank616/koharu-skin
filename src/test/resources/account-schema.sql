CREATE TABLE IF NOT EXISTS users (
    uid BIGINT AUTO_INCREMENT PRIMARY KEY,
    email VARCHAR_IGNORECASE(100) NOT NULL,
    nickname VARCHAR(50) NOT NULL,
    password VARCHAR(255) NOT NULL,
    permission INT NOT NULL DEFAULT 0,
    score INT NOT NULL DEFAULT 0,
    ip VARCHAR(45) NOT NULL DEFAULT '',
    register_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_sign_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    verified BOOLEAN NOT NULL DEFAULT FALSE,
    avatar INT NOT NULL DEFAULT 0,
    verification_token VARCHAR(255) NOT NULL DEFAULT '',
    remember_token VARCHAR(100),
    locale VARCHAR(255),
    is_dark_mode BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE TABLE IF NOT EXISTS players (
    pid BIGINT AUTO_INCREMENT PRIMARY KEY,
    uid BIGINT NOT NULL,
    name VARCHAR_IGNORECASE(50) NOT NULL,
    tid_skin INT NOT NULL DEFAULT 0,
    tid_cape INT NOT NULL DEFAULT 0,
    last_modified TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS options (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    option_name VARCHAR(50) NOT NULL,
    option_value TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS uuid (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    name VARCHAR_IGNORECASE(255) NOT NULL,
    uuid VARCHAR(255) NOT NULL
);
CREATE TABLE IF NOT EXISTS textures (
    tid INT AUTO_INCREMENT PRIMARY KEY,
    name VARCHAR(50) NOT NULL,
    type VARCHAR(10) NOT NULL,
    hash VARCHAR(64) NOT NULL,
    size INT NOT NULL,
    uploader BIGINT NOT NULL,
    public BOOLEAN NOT NULL,
    upload_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    likes INT NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS user_closet (
    user_uid BIGINT NOT NULL,
    texture_tid INT NOT NULL,
    item_name TEXT
);
CREATE TABLE IF NOT EXISTS reports (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    tid INT NOT NULL,
    uploader BIGINT NOT NULL,
    reporter BIGINT NOT NULL,
    reason TEXT NOT NULL,
    status INT NOT NULL,
    report_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS notifications (
    id CHAR(36) PRIMARY KEY,
    type VARCHAR(255) NOT NULL,
    notifiable_type VARCHAR(255) NOT NULL,
    notifiable_id BIGINT NOT NULL,
    data TEXT NOT NULL,
    read_at TIMESTAMP NULL,
    created_at TIMESTAMP NULL,
    updated_at TIMESTAMP NULL
);
CREATE TABLE IF NOT EXISTS oauth_clients (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    user_id BIGINT,
    name VARCHAR(255) NOT NULL,
    secret VARCHAR(100),
    provider VARCHAR(255),
    redirect TEXT NOT NULL,
    personal_access_client BOOLEAN NOT NULL,
    password_client BOOLEAN NOT NULL,
    revoked BOOLEAN NOT NULL,
    created_at TIMESTAMP,
    updated_at TIMESTAMP
);
CREATE TABLE IF NOT EXISTS oauth_access_tokens (
    id VARCHAR(100) PRIMARY KEY,
    user_id BIGINT,
    client_id BIGINT NOT NULL,
    name VARCHAR(255),
    scopes TEXT,
    revoked BOOLEAN NOT NULL,
    created_at TIMESTAMP,
    updated_at TIMESTAMP,
    expires_at TIMESTAMP
);
CREATE TABLE IF NOT EXISTS oauth_auth_codes (
    id VARCHAR(100) PRIMARY KEY,
    user_id BIGINT NOT NULL,
    client_id BIGINT NOT NULL,
    scopes TEXT,
    revoked BOOLEAN NOT NULL,
    expires_at TIMESTAMP
);
CREATE TABLE IF NOT EXISTS oauth_refresh_tokens (
    id VARCHAR(100) PRIMARY KEY,
    access_token_id VARCHAR(100) NOT NULL,
    revoked BOOLEAN NOT NULL,
    expires_at TIMESTAMP
);
CREATE TABLE IF NOT EXISTS scopes (
    id INT AUTO_INCREMENT PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    description VARCHAR(255) NOT NULL
);

CREATE TABLE IF NOT EXISTS ygg_log (
    id INT AUTO_INCREMENT PRIMARY KEY, action VARCHAR(255) NOT NULL,
    user_id INT NOT NULL, player_id INT NOT NULL, parameters VARCHAR(255) DEFAULT '',
    ip VARCHAR(255) DEFAULT '', time DATETIME NOT NULL
);
